// Bundles src-tauri/extensions/kern-openapi.ts into kern-openapi.mjs so the
// kern MCP server can use pi's Swagger catalog with any node on PATH.
// `--check` fails when the committed bundle is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format } from "prettier";
import { build } from "vite";

const extensions = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src-tauri/extensions",
);
const target = resolve(extensions, "kern-openapi.mjs");

export async function bundle() {
  const output = await build({
    configFile: false,
    logLevel: "silent",
    build: {
      write: false,
      minify: false,
      target: "node18",
      lib: {
        entry: resolve(extensions, "kern-openapi.ts"),
        formats: ["es"],
        fileName: () => "kern-openapi.mjs",
      },
      rollupOptions: { external: [/^node:/] },
    },
  });
  const code = (Array.isArray(output) ? output : [output])[0].output[0].code;
  return format(
    `// GENERATED by scripts/build-kern-openapi.mjs from kern-openapi.ts. Do not edit.\n${code}`,
    { parser: "babel" },
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const code = await bundle();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== code) {
      console.error("kern-openapi.mjs is stale; run pnpm build:kern-openapi");
      process.exit(1);
    }
  } else writeFileSync(target, code);
}
